r"""O mapa das competições: as rotinas de cm3/code/comp/ e dos *_rules.cpp (regras de transferência por nação),
o que já está em Rust e o que roda numa carreira de 8 ligas (cobertura.py + simular.py --cobertura).

Uso: python competicoes.py [contagens]   (padrão: levas/competicoes/cobertura_8ligas_contagens.txt)
Grava docs/cobertura_competicoes.txt (a lista para candidatos.py --competicoes) e docs/MAPA_COMPETICOES.md/.en.md.
"""
import collections
import csv
import os
import sys

import placar_arquivos as P

R = P.R
CONT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(R, 'levas', 'competicoes', 'cobertura_8ligas_contagens.txt')

GRUPOS = {  # pasta → (pt, en)
    '(raiz)': ('Base: Liga, Copa, comp, calendário, sorteios', 'Base: League, Cup, comp, calendar, draws'),
    'leagues': ('Ligas nacionais (formato de cada divisão)', 'National leagues (each division\'s format)'),
    'cups': ('Copas nacionais', 'National cups'),
    'eurocomp': ('Competições europeias', 'European competitions'),
    'intercomp': ('Continentais fora da Europa', 'Continental, outside Europe'),
    'worldcup': ('Copa do Mundo e eliminatórias', 'World Cup and qualifiers'),
    'friendly': ('Torneios amistosos', 'Friendly tournaments'),
    'rules': ('Regras de transferência por nação (`transfer/*_rules.cpp`)', 'Transfer rules by nation (`transfer/*_rules.cpp`)'),
}


def main():
    import re
    feitas = {int(x, 16) for x in re.findall(r'Prologue \{ address: (0x[0-9a-f]+)', open(os.path.join(R, 'rust', 'src', 'motor.rs'), encoding='utf-8').read())}
    pasta = {}
    for r in csv.DictReader(open(os.path.join(R, 'docs', 'mapa_funcoes.csv'), encoding='utf-8')):
        a = r['arquivo']
        if a.startswith('cm3/code/comp/'):
            pasta[a.split('/')[-1]] = '/'.join(a.split('/')[3:-1]) or '(raiz)'
        elif a.endswith('_rules.cpp'):
            pasta[a.split('/')[-1]] = 'rules'
    chamadas = {}
    for l in open(CONT, encoding='utf-8', errors='replace'):
        p = l.split()
        if len(p) == 4 and p[0] == 'cobertura':
            chamadas[int(p[1], 16)] = int(p[3])
    # funções verdadeiras do mapa, com o tamanho até o próximo início verdadeiro (como no placar por arquivo)
    linhas = [r for r in P.mapa() if not P.falsa(r)]
    reais = sorted(int(r['address'], 16) for r in linhas)
    fim = dict(zip(reais, reais[1:] + [0x967000]))
    g = collections.defaultdict(lambda: collections.Counter())
    arq = collections.defaultdict(lambda: collections.Counter())
    lista = []
    for r in linhas:
        doc = r['doc']
        if doc not in pasta:
            continue
        a = int(r['address'], 16)
        n = fim[a] - a
        rodou = chamadas.get(a, 0) > 0
        for c in (g[pasta[doc]], arq[doc]):
            c['fun'] += 1; c['kb'] += n
            if a in feitas:
                c['rust'] += 1; c['kbr'] += n
            if rodou:
                c['roda'] += 1
                if a not in feitas:
                    c['falta'] += 1; c['kbf'] += n
        if rodou and a not in feitas:
            lista.append((a, doc, chamadas[a]))
    d = open(os.path.join(R, 'jogo', 'cm0102.exe'), 'rb').read()
    with open(os.path.join(R, 'docs', 'cobertura_competicoes.txt'), 'w', encoding='utf-8') as f:
        f.write('# competicoes.py: cobertura.py cm3/code/comp/ _rules.cpp + simular.py --cobertura (8 ligas ate 2002-06-01, modo rust): endereco, prologo, arquivo, chamadas\n')
        for a, doc, n in sorted(lista):
            f.write('%x %s %s %d\n' % (a, d[a - 0x400000:a - 0x400000 + 6].hex(), doc, n))
    tot = sum((c for c in g.values()), collections.Counter())
    for pt in (True, False):
        L = ['# Mapa das competições' if pt else '# Competitions map', '']
        L.append(('Gerado por `python engenharia-reversa/competicoes.py` (o mapa de funções de maxevans60, CC BY 4.0, e a cobertura de uma carreira '
                  'com as 8 ligas `ENG ESP ITA FRA BRA JPN AUS USA` até 2002-06-01, `levas/competicoes/`; as rotinas já em Rust não levam contador). '
                  '"falta" = chamada ao menos uma vez nessa carreira e ainda não está em Rust (a lista para `candidatos.py --competicoes` fica em `docs/cobertura_competicoes.txt`). '
                  'Como cada competição funciona por dentro (objeto, vtable, estágios, vagas): `docs/.md`.') if pt else
                 ('Generated by `python engenharia-reversa/competicoes.py` (maxevans60\'s function map, CC BY 4.0, and the coverage of a career '
                  'with the 8 leagues `ENG ESP ITA FRA BRA JPN AUS USA` to 2002-06-01, `levas/competicoes/`; routines already in Rust carry no counter). '
                  '"missing" = called at least once in that career and not in Rust yet (the list for `candidatos.py --competicoes` is in `docs/cobertura_competicoes.txt`). '
                  'How each competition works inside (object, vtable, stages, places): `docs/.en.md`.'))
        L += ['', (f'**Total:** {tot["fun"]} funções, {tot["kb"] / 1024:.1f} KB; em Rust {tot["rust"]} ({100 * tot["kbr"] / tot["kb"]:.1f}% dos bytes); '
                   f'faltam {tot["falta"]} ({tot["kbf"] / 1024:.1f} KB).') if pt else
                  (f'**Total:** {tot["fun"]} functions, {tot["kb"] / 1024:.1f} KB; in Rust {tot["rust"]} ({100 * tot["kbr"] / tot["kb"]:.1f}% of the bytes); '
                   f'{tot["falta"]} missing ({tot["kbf"] / 1024:.1f} KB).'), '']
        L += ['| Grupo | Funções | KB | Rust | Falta (KB) | Progresso |' if pt else '| Group | Functions | KB | Rust | Missing (KB) | Progress |',
              '|---|---|---|---|---|---|']
        for k, (npt, nen) in GRUPOS.items():
            c = g.get(k)
            if not c:
                continue
            p = 100 * c['kbr'] / c['kb']
            L.append(f'| {npt if pt else nen} | {c["fun"]} | {c["kb"] / 1024:.1f} | {c["rust"]} | {c["falta"]} ({c["kbf"] / 1024:.1f}) | {P.barra(p)} **{p:.1f}%** |')
        L += ['', '## Por arquivo' if pt else '## By file', '',
              ('Só os arquivos com alguma rotina que falta; ordem: grupo, depois o que falta.') if pt else ('Only files with some missing routine; order: group, then what is missing.'), '',
              '| Arquivo | Grupo | Funções | Rust | Falta (KB) |' if pt else '| File | Group | Functions | Rust | Missing (KB) |', '|---|---|---|---|---|']
        ordem = list(GRUPOS)
        for doc, c in sorted(arq.items(), key=lambda x: (ordem.index(pasta[x[0]]), -x[1]['kbf'], x[0])):
            if c['roda']:
                L.append(f'| `{doc}` | {pasta[doc]} | {c["fun"]} | {c["rust"]} | {c["falta"]} ({c["kbf"] / 1024:.1f}) |')
        nunca = sorted(doc for doc, c in arq.items() if not c['roda'] and not c['rust'])
        L += ['', (f'**Não rodam nesta carreira ({len(nunca)} arquivos):** competições de nações fora das 8 ligas, ou que só começam depois de 2002-06-01. '
                   'Para elas é preciso outra carreira (outras ligas ou mais longa).') if pt else
                  (f'**Do not run in this career ({len(nunca)} files):** competitions of nations outside the 8 leagues, or that only start after 2002-06-01. '
                   'They need another career (other leagues or a longer one).'), '', ', '.join(f'`{x}`' for x in nunca), '']
        open(os.path.join(R, 'docs', 'MAPA_COMPETICOES.md' if pt else 'MAPA_COMPETICOES.en.md'), 'w', encoding='utf-8').write('\n'.join(L))
    print(f'{tot["fun"]} funcoes, rust {tot["rust"]}, rodam {tot["roda"]}, faltam {tot["falta"]} ({tot["kbf"] / 1024:.1f} KB)')


if __name__ == '__main__':
    main()
