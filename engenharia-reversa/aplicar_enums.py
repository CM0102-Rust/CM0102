r"""Names for the enum values of the records' fields (11/11/2026, the outside reader's round 12, obstacle 2: "offer
status 7/8/0xf, round codes 0x82/0x96..."). The readers' verdicts
`{key: {record: "Offer", getter: "status", enum_name: "offer_status", values: {number: {name, meaning, confidence,
evidence}}}}` become constants in rust/src/motor/enums.rs, one module per enum (`offer_status::REJECTED`), typed as the
getter, each with its meaning and reliability (verified / read / inferred). Then, in every function, on a variable of
that record type (`x: Offer`, `let x = Offer(..)`) or on a call chain ending in the getter when only that record has a
getter of that name, `x.status() == 7` becomes `x.status() == offer_status::REJECTED` and `x.set_status(7)` becomes
`x.set_status(offer_status::REJECTED)`. The match engine keeps its own table (match_codes.rs, aplicar_codigos.py).
Usage: python aplicar_enums.py VERDICTS.json [...] [--gravar]
[pt] Os valores de enumeração dos campos dos registros viram constantes com nome e confiança (enums.rs), e os literais
das comparações e atribuições desses campos viram os nomes.
"""
import json
import os
import re
import sys

R = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(R, 'rust', 'src')
SAIDA = os.path.join(SRC, 'motor', 'enums.rs')
sys.path.insert(0, os.path.join(R, 'engenharia-reversa'))
import aplicar_codigos as ac  # noqa: E402
import mover_rotinas  # noqa: E402
import tipar_registros as tr  # noqa: E402

LIT = r'(-?(?:0x[0-9a-f]+|\d+))'


def main():
    arqs = [a for a in sys.argv[1:] if not a.startswith('--')]
    grava = '--gravar' in sys.argv
    getters = ac.tipos_dos_getters()
    donos = {}
    for (tipo, g) in getters:
        donos.setdefault(g, set()).add(tipo)
    modulos = {}  # module -> (type, {value: (name, meaning, confidence)}, [(record, getter)])
    for a in arqs:
        for chave, tab in json.load(open(a, encoding='utf-8')).items():
            if not isinstance(tab, dict) or 'values' not in tab or not tab.get('record') or not tab.get('getter'):
                continue
            alvo = (tab['record'], tab['getter'])
            if alvo not in getters:
                print('sem getter:', alvo)
                continue
            mod = re.sub(r'[^a-z0-9_]', '_', (tab.get('enum_name') or chave).lower())
            tipo_g = getters[alvo]
            if mod not in modulos:
                modulos[mod] = (tipo_g, {}, [])
            tipo_m, vals, alvos = modulos[mod]
            if alvo not in alvos:
                alvos.append(alvo)
            for num, v in tab['values'].items():
                try:
                    val = ac.normal(int(num, 0), tipo_m)
                except ValueError:
                    continue
                nome = re.sub(r'[^A-Z0-9_]', '_', (v.get('name') or '').upper()).strip('_')
                if not nome or nome[0].isdigit() or val in vals or nome in {x[0] for x in vals.values()}:
                    continue
                vals[val] = (nome, re.sub(r'\s+', ' ', v.get('meaning', '')).strip().rstrip('.'), v.get('confidence', 'read'))
    L = ['use super::*;', '',
         '// The enum values of the records\' fields by name, generated by engenharia-reversa/aplicar_enums.py from readings',
         '// of the original routines (levas/reorganizacao/enums_*.json). Each constant says what it means and how far to',
         '// trust the name: verified (concrete evidence), read (one clear reading), inferred (a guess).',
         '// [pt] Os valores de enumeração dos campos dos registros, com nome, significado e confiança.', '']
    tabelas = {}
    for mod, (tipo_m, vals, alvos) in sorted(modulos.items()):
        if not vals:
            continue
        L += ['/// Values of %s.' % ', '.join('`%s::%s()`' % al for al in alvos), '#[allow(dead_code)]', 'pub(crate) mod %s {' % mod]
        for val in sorted(vals):
            nome, sig, conf = vals[val]
            L += ['    /// %s. Name: %s.' % (sig[:1].upper() + sig[1:] if sig else nome, conf),
                  '    pub(crate) const %s: %s = %d;' % (nome, tipo_m, val)]
        L += ['}', '']
        for al in alvos:
            tabelas[al] = (mod, tipo_m, {v: n for v, (n, _, _) in vals.items()})
    print('%d tabelas, %d constantes' % (len(tabelas), sum(len(t[2]) for t in tabelas.values())))
    if grava:
        open(SAIDA, 'w', encoding='utf-8').write('\n'.join(L) + '\n')
    tipos = sorted({al[0] for al in tabelas})
    por_getter = {}
    for (tipo, g), info in tabelas.items():
        por_getter.setdefault(g, {})[tipo] = info
    n = 0
    for raiz, _, fs in os.walk(SRC):
        for f in fs:
            if not f.endswith('.rs') or f in ('records.rs', 'fields.rs', 'enums.rs', 'match_codes.rs', 'exe_calls.rs', 'bits.rs'):
                continue
            p = os.path.join(raiz, f)
            t = open(p, encoding='utf-8').read()
            partes, pos = [], 0
            for _, a, b in mover_rotinas.blocos(t):
                bl = t[a:b]
                mk = tr.mascara(bl)
                tip = {}
                if tipos:
                    alt = '|'.join(tipos)
                    for m in re.finditer(r'(?<![\w.])([a-z_][a-z0-9_]*)\s*:\s*(%s)\b' % alt, mk):
                        tip[m.group(1)] = m.group(2)
                    for m in re.finditer(r'\blet\s+([a-z_][a-z0-9_]*)\s*=\s*(%s)\(' % alt, mk):
                        tip[m.group(1)] = m.group(2)

                def info_de(recv, g):
                    tab = por_getter.get(g)
                    if not tab:
                        return None
                    if recv in tip and tip[recv] in tab:
                        return tab[tip[recv]]
                    # a chain (`x.club().status()`): only when a single record type has a getter of that name
                    if len(donos.get(g, ())) == 1 and len(tab) == 1:
                        return next(iter(tab.values()))
                    return None
                ed = []
                for m in re.finditer(r'(?<![\w])([a-z_][a-z0-9_]*)?((?:\.[a-z_0-9]+\([^()]*\))*)\.([a-z_0-9]+)\(\)(\s*as\s*\w+)?\)?\s*(==|!=)\s*' + LIT + r'\b', mk):
                    info = info_de(m.group(1) if not m.group(2) else None, m.group(3))
                    if not info:
                        continue
                    mod, tipo_m, nomes = info
                    val = ac.normal(int(m.group(6), 0), tipo_m)
                    if val in nomes and not m.group(4):
                        ed.append((m.start(6), m.end(6), '%s::%s' % (mod, nomes[val])))
                for m in re.finditer(r'(?<![\w])([a-z_][a-z0-9_]*)?((?:\.[a-z_0-9]+\([^()]*\))*)\.set_([a-z_0-9]+)\(\(?' + LIT + r'\)?\)', mk):
                    info = info_de(m.group(1) if not m.group(2) else None, m.group(3))
                    if not info:
                        continue
                    mod, tipo_m, nomes = info
                    val = ac.normal(int(m.group(4), 0), tipo_m)
                    if val in nomes:
                        ed.append((m.start(4), m.end(4), '%s::%s' % (mod, nomes[val])))
                if not ed:
                    continue
                novo = bl
                for a2, b2, txt in sorted(set(ed), reverse=True):
                    novo = novo[:a2] + txt + novo[b2:]
                n += len(ed)
                partes += [t[pos:a], novo]
                pos = b
            partes.append(t[pos:])
            if grava and ''.join(partes) != t:
                open(p, 'w', encoding='utf-8').write(''.join(partes))
    print('%d literais viraram nomes' % n)


if __name__ == '__main__':
    main()
