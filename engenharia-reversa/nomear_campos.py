r"""Dá nome aos campos dos registros do jogo no motor (etapa 4 da reorganização, rodada 2, 07/11/2026).

`clube + 0x57` vira `clube + club::DIVISION`: quando o nome da variável diz o registro (clube, pessoa, nacao,
contrato, comp, estadio, cidade, com ou sem sufixo) e o deslocamento é o começo exato de um campo do leiaute em
docs/FORMATOS.md (os nomes em inglês dos editores da comunidade). As constantes ficam em rust/src/motor/fields.rs, um
módulo por registro. Os comentários não mudam; as listas de mutação recebem a mesma troca. O valor é o mesmo: o código
gerado não muda.

Uso: python nomear_campos.py [--gravar]
"""
import os
import re
import sys

R = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(R, 'rust', 'src')
# variável -> (registro no FORMATOS.md, módulo em fields.rs)
REGISTROS = {'clube': ('TClub', 'club'), 'pessoa': ('TStaff', 'staff'), 'nacao': ('TNation', 'nation'),
             'contrato': ('TContract', 'contract'), 'comp': ('TComp', 'competition'),
             'estadio': ('TStadiums', 'stadium'), 'cidade': ('TCities', 'city'),
             # os nomes ingleses dos locais (traduzir_locais.py, 08/11/2026)
             'club': ('TClub', 'club'), 'person': ('TStaff', 'staff'), 'nation': ('TNation', 'nation'),
             'contract': ('TContract', 'contract'), 'stadium': ('TStadiums', 'stadium'), 'city': ('TCities', 'city'),
             # a ficha do jogador (+0x61 da pessoa) e o técnico (uma pessoa)
             'sheet': ('TPlayer', 'player_sheet'), 'ficha': ('TPlayer', 'player_sheet'),
             'manager': ('TStaff', 'staff'), 'tecnico': ('TStaff', 'staff')}
USO = re.compile(r'\b((clube|pessoa|nacao|contrato|comp|estadio|cidade|club|person|nation|contract|stadium|city|sheet|ficha|manager|tecnico)'
                 r'(?:_[a-z0-9_]+|\d+)?) \+ (0x[0-9a-f]+)\b')


def leiautes():
    s = open(os.path.join(R, 'docs', 'FORMATOS.md'), encoding='utf-8').read()
    r = {}
    for nome, corpo in re.findall(r'^### `(T\w+)` \(\d+ bytes\)\n(.*?)(?=^### |\Z)', s, re.M | re.S):
        campos = {}
        for d, b, t, c in re.findall(r'^\| (0x[0-9a-f]+) \| (\d+) \| `([^`]*)` \| (\w+) \|', corpo, re.M):
            campos[int(d, 16)] = (re.sub(r'(?<=[a-z0-9])(?=[A-Z])', '_', c).upper(), int(b), t)
        r[nome] = campos
    return r


def arquivos():
    yield os.path.join(SRC, 'motor.rs')
    for d, _, fs in os.walk(os.path.join(SRC, 'motor')):
        for f in fs:
            if f.endswith('.rs') and f != 'fields.rs':
                yield os.path.join(d, f)


def main():
    lei = leiautes()
    usados = {}

    def trocar_linha(l):
        cod, sep, com = l.partition('//')
        if cod.lstrip().startswith('///'):
            return l

        def f(m):
            reg, mod = REGISTROS[m.group(2)]
            d = int(m.group(3), 16)
            campo = lei.get(reg, {}).get(d)
            if not campo:
                return m.group(0)
            usados.setdefault(mod, {})[campo[0]] = (d, campo[1], campo[2], reg)
            return '%s + %s::%s' % (m.group(1), mod, campo[0])
        return USO.sub(f, cod) + sep + com

    n = 0
    for p in arquivos():
        t = open(p, encoding='utf-8').read()
        novo = '\n'.join(trocar_linha(l) for l in t.split('\n'))
        n += sum(1 for a, b in zip(t.split('\n'), novo.split('\n')) if a != b)
        if novo != t and '--gravar' in sys.argv:
            open(p, 'w', encoding='utf-8').write(novo)
    print('%d linhas, %d campos com nome' % (n, sum(len(v) for v in usados.values())))
    if '--gravar' not in sys.argv:
        return
    import trocar_nas_mutacoes
    trocar_nas_mutacoes.aplicar(trocar_linha)
    L = ['use super::*;', '',
         '// Field offsets of the game\'s records, by name (layouts in docs/FORMATOS.en.md, field names from the community',
         '// editors). Generated by engenharia-reversa/nomear_campos.py. `club + club::DIVISION` is the club\'s division.',
         '// [pt] Os deslocamentos dos campos dos registros do jogo, pelo nome (leiautes em docs/FORMATOS.md).', '']
    # junta com o fields.rs que já existe (outros módulos vêm de aplicar_campos_classes.py e das rodadas anteriores)
    pf = os.path.join(SRC, 'motor', 'fields.rs')
    texto = open(pf, encoding='utf-8').read() if os.path.exists(pf) else '\n'.join(L) + '\n'
    for mod in sorted(usados):
        consts = ['    pub(crate) const %s: usize = %#x; // %d byte(s), %s' % (nome, d, b, t)
                  for nome, (d, b, t, _) in sorted(usados[mod].items(), key=lambda x: x[1][0])]
        abre = 'pub(crate) mod %s {\n' % mod
        if abre in texto:
            i = texto.index(abre) + len(abre)
            fim = texto.index('\n}', i)
            dentro = texto[i:fim]
            novas = [c for c in consts if 'const %s:' % c.split('const ')[1].split(':')[0] not in dentro]
            texto = texto[:fim] + ''.join('\n' + c for c in novas) + texto[fim:]
        else:
            reg = next(iter(usados[mod].values()))[3]
            texto = texto.rstrip('\n') + '\n\n' + '\n'.join(['/// `%s` record. [pt] Registro `%s`.' % (reg, reg), '#[allow(dead_code)]', abre.rstrip('\n')] + consts + ['}', ''])
    open(pf, 'w', encoding='utf-8').write(texto)
    print('gravado')


if __name__ == '__main__':
    main()
