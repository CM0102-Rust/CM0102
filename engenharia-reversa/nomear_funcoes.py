r"""Troca os endereços crus das funções do exe chamadas pelo motor (`transmute(0x5223a0usize)`) por constantes com nome
(`transmute(FN_CUP_RANK_TEAMS)`), em rust/src/motor/exe_fns.rs (etapa 4 da reorganização, 07/11/2026).

Os nomes vêm do mapa de maxevans60 (CC BY 4.0, ver CREDITOS.md); as rotinas da biblioteca C do compilador, que o mapa
não nomeia, pelo nome que o nosso código já dava a cada uma (CRT abaixo). Sem nome certo: FN_<endereço>.

Uso: python nomear_funcoes.py --gravar
"""
import csv
import os
import re
import sys

R = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(R, 'rust', 'src')
CHAMADA = re.compile(r'transmute\((0x[0-9a-f]+)usize\)')
# a biblioteca C do compilador (MSVC 6): pelo uso no nosso código ([inferência] onde não há nome certo)
CRT = {0x944c94: 'operator_delete', 0x944c9f: 'sprintf', 0x944cf1: 'operator_new', 0x944cff: 'strtok',
       0x944e46: 'malloc', 0x9452ca: 'free', 0x945333: 'qsort', 0x945501: 'calloc', 0x945667: 'realloc',
       0x945934: 'exit', 0x945a09: 'fclose', 0x945a60: 'strstr', 0x945b00: 'fopen', 0x945b13: 'makepath',
       0x945ba4: 'rename', 0x945bfe: 'fread', 0x945ce6: 'fwrite', 0x94627a: 'atexit',
       0x9462bb: 'vector_destructor_iterator', 0x9463af: 'vector_constructor_iterator', 0x94643a: 'remove',
       0x946464: 'bsearch', 0x9469fa: 'srand', 0x946a04: 'rand', 0x946a22: 'fseek', 0x946aae: 'ftell',
       0x946fa0: 'strncmp', 0x951c50: 'stricmp'}


def arquivos():
    yield os.path.join(SRC, 'motor.rs')
    for d, _, fs in os.walk(os.path.join(SRC, 'motor')):
        for f in fs:
            if f.endswith('.rs') and f != 'exe_fns.rs':
                yield os.path.join(d, f)


def nome_de(texto):
    t = texto.replace('::~', '::destructor_').replace('~', 'destructor_')
    t = re.sub(r'operator\s*([^\w\s]+)', lambda m: 'operator_' + '_'.join('%02x' % ord(c) for c in m.group(1)), t)
    t = re.sub(r'[^A-Za-z0-9]+', '_', t).strip('_')
    return 'FN_' + t.upper()


def mapa():
    m = {}
    tsv = os.path.join(R, 'referencias', 'cm0102-function-map', 'map', 'functions.tsv')
    for r in csv.reader(open(tsv, encoding='utf-8'), delimiter='\t'):
        if r and r[0].startswith('0x') and len(r) > 3 and r[3] and 'fragment' not in r[3].lower():
            m[int(r[0], 16)] = (r[3], r[5] if len(r) > 5 else '')
    return m


def main():
    nomes_mapa = mapa()
    textos = {f: open(f, encoding='utf-8').read() for f in arquivos()}
    usados = sorted({int(a, 16) for t in textos.values() for a in CHAMADA.findall(t)})
    nome, vistos, sem = {}, {}, 0
    for a in usados:
        if a in CRT:
            n, sobre = 'FN_CRT_' + CRT[a].upper(), 'C runtime: %s' % CRT[a]
        elif a in nomes_mapa:
            n, sobre = nome_de(nomes_mapa[a][0]), nomes_mapa[a][0]
        else:
            n, sobre, sem = 'FN_%X' % a, 'no name in the map', sem + 1
        if n in vistos:
            n = '%s_%X' % (n, a)
        vistos[n] = a
        nome[a] = (n, sobre)
    print('%d funções; %d sem nome' % (len(usados), sem))
    if '--gravar' not in sys.argv:
        return
    def trocar_linha(l):
        return CHAMADA.sub(lambda m: 'transmute(%s)' % nome[int(m.group(1), 16)][0] if int(m.group(1), 16) in nome else m.group(0), l)

    for f, t in textos.items():
        novo = trocar_linha(t)
        if novo != t:
            open(f, 'w', encoding='utf-8').write(novo)
    import trocar_nas_mutacoes
    trocar_nas_mutacoes.aplicar(trocar_linha)
    cab = ('// The exe\'s functions the engine still calls, by name (address in cm0102.exe 3.9.68). Names from maxevans60\'s\n'
           '// map (CC BY 4.0, see CREDITOS.md); the C runtime ones from how our code uses them. Generated by\n'
           '// engenharia-reversa/nomear_funcoes.py.\n'
           '// [pt] As funções do exe que o motor ainda chama, pelo nome (endereço no cm0102.exe 3.9.68). Nomes do mapa de\n'
           '// maxevans60 (CC BY 4.0, ver CREDITOS.md); as da biblioteca C, pelo uso no nosso código.\n\n')
    corpo = ''.join('pub const %s: usize = %#x; // %s\n' % (n, a, s) for a, (n, s) in sorted(nome.items()))
    open(os.path.join(SRC, 'motor', 'exe_fns.rs'), 'w', encoding='utf-8').write(cab + corpo)
    print('gravado')


if __name__ == '__main__':
    main()
