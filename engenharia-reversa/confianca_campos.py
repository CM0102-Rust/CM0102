r"""How much to trust each field name (09/11/2026, Lucas: classify the names by reliability). The level comes from where
the name came from, which the comment in rust/src/motor/fields.rs already tells:

- community: `// 2 byte(s), UInt16`: the layouts of the community editors (docs/FORMATOS.md), years of use;
- verified: `[verified: how]` in the comment: confirmed by a second, independent source (another reading of the
  original, the community function map, an observation in the game);
- read: a description without a mark: proposed by reading the original code, with the evidence in the description;
- inferred: `[inference]` in the comment: proposed by reading, a plausible guess.

Writes docs/CONFIANCA_DOS_CAMPOS.md and .en.md (counts per record and the list of the inferred names), used by
registros.py to put the level in each method's doc. Usage: python confianca_campos.py [--gravar]
[pt] A confiança de cada nome de campo, pela origem que o comentário do fields.rs já diz: comunidade, conferido, lido,
inferido.
"""
import collections
import os
import re
import sys

R = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FIELDS = os.path.join(R, 'rust', 'src', 'motor', 'fields.rs')
NIVEIS = ('community', 'verified', 'read', 'inferred')
PT = {'community': 'comunidade', 'verified': 'conferido', 'read': 'lido', 'inferred': 'inferido'}


def nivel(comentario):
    c = comentario.strip()
    if '[verified' in c:
        return 'verified'
    if '[inference' in c:
        return 'inferred'
    if re.match(r'\d+ byte\(s\), \S', c):
        return 'community'
    return 'read'


def campos():
    """[(module, FIELD, offset, level, comment)]"""
    out, mod = [], None
    for l in open(FIELDS, encoding='utf-8'):
        m = re.match(r'\s*pub\(crate\) mod (\w+)', l)
        if m:
            mod = m.group(1)
            continue
        m = re.match(r'\s*pub\(crate\) const (\w+): usize = (0x[0-9a-f]+|\d+);\s*(?://\s*(.*))?$', l)
        if m and mod:
            out.append((mod, m.group(1), int(m.group(2), 0), nivel(m.group(3) or ''), (m.group(3) or '').strip()))
    return out


def niveis_por_campo():
    return {(m, c): n for m, c, _, n, _ in campos()}


def main():
    cs = campos()
    por = collections.defaultdict(collections.Counter)
    for m, c, o, n, _ in cs:
        por[m][n] += 1
    total = collections.Counter(n for *_, n, _ in cs)
    print(dict(total))
    if '--gravar' not in sys.argv:
        return
    for lang in ('pt', 'en'):
        nome = lambda n: PT[n] if lang == 'pt' else n
        L = []
        if lang == 'pt':
            L += ['*[English version](CONFIANCA_DOS_CAMPOS.en.md).*', '', '# Confiança dos nomes dos campos', '',
                  'Gerado por `engenharia-reversa/confianca_campos.py` a partir do `rust/src/motor/fields.rs`. O nível vem da',
                  'origem do nome, que o comentário de cada campo já diz:', '',
                  '- **comunidade** (`// 2 byte(s), UInt16`): os leiautes dos editores da comunidade (docs/FORMATOS.md), anos de uso;',
                  '- **conferido** (`[verified: como]`): confirmado por uma segunda fonte independente (outra leitura do original, o mapa',
                  '  de funções da comunidade, uma observação no jogo);',
                  '- **lido** (descrição sem marca): proposto pela leitura do código original, com a evidência na descrição;',
                  '- **inferido** (`[inference]`): proposto pela leitura, um palpite plausível.', '',
                  'A largura de cada acesso foi conferida contra a instrução original (rodada 28, `larguras_campos.py --original`);',
                  'o nível aqui é o do **nome** (o significado), não o da largura. Cada método do `records.rs` traz o nível no comentário.',
                  '', '## Totais', '', '| Nível | Campos |', '|---|---|']
        else:
            L += ['*[Versão em português](CONFIANCA_DOS_CAMPOS.md).*', '', '# Reliability of the field names', '',
                  'Generated by `engenharia-reversa/confianca_campos.py` from `rust/src/motor/fields.rs`. The level comes from where',
                  'the name came from, which each field\'s comment already tells:', '',
                  '- **community** (`// 2 byte(s), UInt16`): the layouts of the community editors (docs/FORMATOS.en.md), years of use;',
                  '- **verified** (`[verified: how]`): confirmed by a second, independent source (another reading of the original, the',
                  '  community function map, an observation in the game);',
                  '- **read** (a description without a mark): proposed by reading the original code, with the evidence in the description;',
                  '- **inferred** (`[inference]`): proposed by reading, a plausible guess.', '',
                  'The width of each access was checked against the original instruction (round 28, `larguras_campos.py --original`);',
                  'the level here is the **name\'s** (the meaning), not the width\'s. Each method in `records.rs` carries the level.',
                  '', '## Totals', '', '| Level | Fields |', '|---|---|']
        for n in NIVEIS:
            L.append('| %s | %d |' % (nome(n), total[n]))
        L += ['', '## %s' % ('Por registro' if lang == 'pt' else 'Per record'), '',
              '| %s | %s |' % ('Registro' if lang == 'pt' else 'Record', ' | '.join(nome(n) for n in NIVEIS)),
              '|---|' + '---|' * len(NIVEIS)]
        for m in sorted(por):
            L.append('| `%s` | %s |' % (m, ' | '.join(str(por[m][n]) for n in NIVEIS)))
        L += ['', '## %s' % ('Os nomes inferidos (a conferir)' if lang == 'pt' else 'The inferred names (to check)'), '',
              '| %s |' % (' | '.join(('Campo', 'Desloc.', 'Descrição') if lang == 'pt' else ('Field', 'Offset', 'Description'))),
              '|---|---|---|']
        for m, c, o, n, com in cs:
            if n == 'inferred':
                L.append('| `%s::%s` | +0x%x | %s |' % (m, c, o, com.replace('|', '/')))
        nomearq = 'CONFIANCA_DOS_CAMPOS.md' if lang == 'pt' else 'CONFIANCA_DOS_CAMPOS.en.md'
        open(os.path.join(R, 'docs', nomearq), 'w', encoding='utf-8').write('\n'.join(L) + '\n')
    print('gravado')


if __name__ == '__main__':
    main()
