r"""Os números com casas decimais que as cópias leem do exe ganham nome (etapa 4 da reorganização, 08/11/2026; o leitor de
fora, rodadas 6 a 8: ~1.570 `read_f64_at(0x968968) // 0x968968 = 0.5`). Cada endereço lido por `read_f32*`/`read_f64*`
vira uma constante em rust/src/motor/rdata.rs, dentro de `pub(crate) mod rdata`, com o valor no nome
(`rdata::F64_0_5`); o valor continua sendo lido do exe (um patch da comunidade que mude a constante continua valendo),
e o comentário `// 0x968968 = 0.5` que só repetia o valor sai. O código gerado não muda. As listas de mutação
acompanham, trecho a trecho.

Uso: python nomear_rdata.py [--gravar]
"""
import collections
import glob
import os
import re
import struct
import sys

R = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(R, 'rust', 'src')
EXE = os.path.join(R, 'jogo', 'cm0102.exe')
sys.path.insert(0, os.path.join(R, 'engenharia-reversa'))
import traduzir_locais as tl  # noqa: E402
import trocar_nas_mutacoes  # noqa: E402

LEITURA = re.compile(r'\b(read_f(32|64)(?:_at)?)\((0x[0-9a-f]{6})\)')


def texto_valor(v):
    if v == int(v) and abs(v) < 1e15:
        s = '%d' % int(v)
    else:
        s = repr(float('%.10g' % v))
    s = s.replace('-', 'NEG_').replace('+', '').replace('.', '_').replace('e', 'E')
    return s.upper()


def main():
    exe = open(EXE, 'rb').read()
    usos = collections.Counter()
    for p in glob.glob(os.path.join(SRC, '**', '*.rs'), recursive=True):
        for m in LEITURA.finditer(open(p, encoding='utf-8').read()):
            usos[(int(m.group(3), 16), m.group(2))] += 1
    nomes, usados = {}, set()
    # the constants already named stay (a run only adds the new raw reads; 10/11/2026)
    arq = os.path.join(SRC, 'motor', 'rdata_consts.rs')
    if os.path.exists(arq):
        for m in re.finditer(r'pub\(crate\) const (\w+): usize = (0x[0-9a-f]+); // f(32|64) = (\S+)', open(arq, encoding='utf-8').read()):
            nomes[(int(m.group(2), 16), m.group(3))] = (m.group(1), float(m.group(4)))
            usados.add(m.group(1))
    for (end, bits), _ in sorted(usos.items()):
        if (end, bits) in nomes:
            continue
        off = end - 0x400000
        v = struct.unpack_from('<f' if bits == '32' else '<d', exe, off)[0]
        base = 'F%s_%s' % (bits, texto_valor(v))
        nome = base if base not in usados else '%s_AT_%X' % (base, end)
        usados.add(nome)
        nomes[(end, bits)] = (nome, v)
    print('%d endereços, %d leituras' % (len(nomes), sum(usos.values())))
    L = ['use super::*;', '',
         '// The floating-point constants the Rust copies read from the original exe\'s .rdata, named by their value in',
         '// cm0102.exe 3.9.68 (generated by engenharia-reversa/nomear_rdata.py). The value is still read from the exe, so a',
         '// community patch that changes one of them keeps working.',
         '// [pt] As constantes com casas decimais que as cópias leem do .rdata do exe, com o valor no nome; o valor continua',
         '// sendo lido do exe (um patch que mude a constante continua valendo).', '',
         '#[allow(dead_code)]', 'pub(crate) mod rdata {']
    for (end, bits), (nome, v) in sorted(nomes.items(), key=lambda x: x[1][0]):
        L.append('    pub(crate) const %s: usize = %#x; // f%s = %r' % (nome, end, bits, v))
    L.append('}')
    por_end = {end: nome for (end, bits), (nome, v) in nomes.items()}

    def f_linha(l):
        cod, sep, com = l.partition('//')
        trocados = set()

        def r(m):
            end = int(m.group(3), 16)
            k = (end, m.group(2))
            if k not in nomes:
                return m.group(0)
            trocados.add(end)
            return '%s(rdata::%s)' % (m.group(1), nomes[k][0])
        partes = re.split(r'("(?:[^"\\]|\\.)*")', cod)
        cod2 = ''.join(x if x.startswith('"') else LEITURA.sub(r, x) for x in partes)
        if sep and trocados:
            # o comentário que só repetia "0xENDEREÇO = valor" (um ou vários) sai
            resto = com
            for end in trocados:
                resto = re.sub(r'\s*%#x\s*=\s*[-0-9.e+]+[;,]?' % end, '', resto)
            if not resto.strip(' ;,'):
                return cod2.rstrip()
            return cod2 + sep + resto
        return cod2 + sep + com
    n = 0
    for p in glob.glob(os.path.join(SRC, '**', '*.rs'), recursive=True):
        if p.endswith('rdata_consts.rs'):
            continue
        t = open(p, encoding='utf-8', newline='').read()
        nl = '\r\n' if '\r\n' in t else '\n'
        novo = nl.join(f_linha(l) for l in t.split(nl))
        if novo != t:
            n += 1
            if '--gravar' in sys.argv:
                open(p, 'w', encoding='utf-8', newline='').write(novo)
    print('%d arquivos' % n)
    if '--gravar' not in sys.argv:
        return
    open(os.path.join(SRC, 'motor', 'rdata_consts.rs'), 'w', encoding='utf-8').write('\n'.join(L) + '\n')
    os.system('python "%s" --gravar' % os.path.join(R, 'engenharia-reversa', 'modulos_motor.py'))
    trocar_nas_mutacoes.aplicar_por_trecho(f_linha)
    print('gravado')


if __name__ == '__main__':
    main()
