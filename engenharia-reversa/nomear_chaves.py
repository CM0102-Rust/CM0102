r"""Troca as chaves fixas cruas (0x9cf2e4...) do motor por constantes com nome (KEY_NATION_ENGLAND...), em
rust/src/motor/keys.rs (etapa 4 da reorganização, 07/11/2026). Os nomes vêm de docs/chaves_uso.csv (os da set_key_ids,
pelo mapa de maxevans60). Os arquivos gerados (chaves_fixas.rs, adjetivos_nacao.rs) ficam como estão: são tabelas.

As constantes são usize; onde o código pedia outro tipo, a troca leva `as <tipo>` (o compilador diz onde: rode
`--tipos` depois de compilar com erro, e ele acrescenta a conversão nas linhas acusadas).

Uso: python nomear_chaves.py --gravar
     python nomear_chaves.py --tipos     (lê os erros do cargo e corrige os tipos)
"""
import csv
import os
import re
import subprocess
import sys

R = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(R, 'rust', 'src')
CHAVE = re.compile(r'\b(0x9cf[0-9a-f]{3})(usize)?\b')


def arquivos():
    yield os.path.join(SRC, 'motor.rs')
    for d, _, fs in os.walk(os.path.join(SRC, 'motor')):
        for f in fs:
            if f.endswith('.rs') and f != 'keys.rs':
                yield os.path.join(d, f)


def nomes():
    return {int(r['endereco'], 16): r['chave'].upper().replace('G_KEY_', 'KEY_')
            for r in csv.DictReader(open(os.path.join(R, 'docs', 'chaves_uso.csv'), encoding='utf-8'))}


def gravar():
    n = nomes()
    usadas = {}

    def trocar_linha(l):
        # só código: não mexe em comentários (o texto depois de //)
        cod, sep, com = l.partition('//')
        return CHAVE.sub(lambda m: (usadas.setdefault(int(m.group(1), 16), n[int(m.group(1), 16)]))
                         if int(m.group(1), 16) in n else m.group(0), cod) + sep + com

    for f in arquivos():
        t = open(f, encoding='utf-8').read()
        novo = '\n'.join(trocar_linha(l) for l in t.split('\n'))
        if novo != t:
            open(f, 'w', encoding='utf-8').write(novo)
    import trocar_nas_mutacoes
    trocar_nas_mutacoes.aplicar(trocar_linha)
    cab = ('// The game\'s fixed keys: the global pointer of each nation, club, continent, colour and staff member the code\n'
           '// refers to by name (set by set_key_ids, 0x601a40). Names from maxevans60\'s map (CC BY 4.0), see CREDITOS.md.\n'
           '// Generated by engenharia-reversa/nomear_chaves.py.\n'
           '// [pt] As chaves fixas do jogo: o ponteiro global de cada nação, clube, continente, cor e pessoa que o código cita\n'
           '// pelo nome (postas pela set_key_ids, 0x601a40). Nomes do mapa de maxevans60 (CC BY 4.0), ver CREDITOS.md.\n\n')
    corpo = ''.join('pub const %s: usize = %#x;\n' % (nome, a) for a, nome in sorted(usadas.items()))
    open(os.path.join(SRC, 'motor', 'keys.rs'), 'w', encoding='utf-8').write(cab + corpo)
    print('%d chaves com nome' % len(usadas))


def tipos():
    r = subprocess.run(['cargo', 'build', '--release', '--message-format=short'], cwd=os.path.join(R, 'rust'),
                       capture_output=True, text=True, encoding='utf-8', errors='replace')
    # E0308: "expected `u32`, found `usize`" na constante; E0277: "cannot add `isize` to `usize`" (a constante à
    # esquerda de uma soma com outro tipo): em ambos a constante leva `as <tipo pedido>`
    erros = [(f, l, c, t) for f, l, c, t in re.findall(
        r'^(src[^:]+):(\d+):(\d+): error\[E0308\]: mismatched types: expected `(\w+)`, found `usize`', r.stderr, re.M)]
    erros += [(f, l, c, t) for f, l, c, t in re.findall(
        r'^(src[^:]+):(\d+):(\d+): error\[E0277\]: cannot (?:add|subtract|multiply) `(\w+)` (?:to|from|by) `usize`', r.stderr, re.M)]
    feitos = 0
    por_arq = {}
    for f, l, c, t in erros:
        por_arq.setdefault(os.path.join(os.path.join(R, 'rust'), f), set()).add((int(l), int(c), t))
    for f, pos in por_arq.items():
        ls = open(f, encoding='utf-8').read().split('\n')
        for l, c, t in sorted(pos, reverse=True):
            linha = ls[l - 1]
            # a constante na coluna do erro, ou a última antes dela na mesma linha (o operando esquerdo da soma)
            m = re.match(r'(?:KEY|G)_\w+', linha[c - 1:])
            if m:
                ini, fim = c - 1, c - 1 + m.end()
            else:
                antes = list(re.finditer(r'\b(?:KEY|G)_\w+\b(?! as )', linha[:c + 40]))
                if not antes:
                    continue
                ini, fim = antes[-1].start(), antes[-1].end()
            ls[l - 1] = linha[:ini] + '(%s as %s)' % (linha[ini:fim], t) + linha[fim:] if t != 'u32' else linha[:fim] + ' as u32' + linha[fim:]
            feitos += 1
        open(f, 'w', encoding='utf-8').write('\n'.join(ls))
    print('%d erros de tipo, %d corrigidos' % (len(erros), feitos))


if __name__ == '__main__':
    gravar() if '--gravar' in sys.argv else tipos() if '--tipos' in sys.argv else sys.exit(__doc__)
