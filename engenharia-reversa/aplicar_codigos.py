r"""Names for the magic numbers of the match engine (09/11/2026, readability): the readers' verdicts
(`{field: {enum_name, values: {number: {name, meaning, confidence, evidence}}}}`) become constants in
rust/src/motor/match_codes.rs, one module per field (`restart::THROW_IN`), typed as the field's getter, each with its
meaning and reliability (as docs/CONFIANCA_DOS_CAMPOS.md: verified / read / inferred). Then, in every function, on a
variable typed `Engine` or `MatchPlayer`, `x.field() == 5` becomes `x.field() == restart::PENALTY`, `x.set_field(5)`
becomes `x.set_field(restart::PENALTY)`, and `x.move_skill(46)` becomes `x.move_skill(moves::NAME)`.
Usage: python aplicar_codigos.py VERDICTS.json [...] [--gravar]
[pt] Os números mágicos do motor viram constantes com nome e confiança (match_codes.rs), e os literais das comparações e
atribuições desses campos viram os nomes.
"""
import json
import os
import re
import sys

R = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(R, 'rust', 'src')
SAIDA = os.path.join(SRC, 'motor', 'match_codes.rs')
sys.path.insert(0, os.path.join(R, 'engenharia-reversa'))
import mover_rotinas  # noqa: E402
import tipar_registros as tr  # noqa: E402

# verdict key -> (record type, getter); move codes index MOVE_SKILL
CAMPOS = {
    'restart_type': ('Engine', 'restart_type'), 'ball_height': ('Engine', 'ball_height'),
    'shootout_state': ('Engine', 'shootout_state'), 'pending_play_kind': ('Engine', 'pending_play_kind'),
    'period_end': ('Engine', 'period_end'), 'match_player_action': ('MatchPlayer', 'action'),
    'action': ('MatchPlayer', 'action'),
}
BITS = {'u8': 8, 'i8': 8, 'u16': 16, 'i16': 16, 'u32': 32, 'i32': 32, 'usize': 32}


def tipos_dos_getters():
    t = open(os.path.join(SRC, 'motor', 'records.rs'), encoding='utf-8').read()
    out, atual = {}, None
    for l in t.split('\n'):
        m = re.match(r'impl (\w+) \{', l)
        if m:
            atual = m.group(1)
        m = re.match(r'\s*pub\(crate\) unsafe fn (\w+)\(self\) -> (\w+)', l)
        if m and atual:
            out[(atual, m.group(1))] = m.group(2)
    return out


def normal(v, tipo):
    """The value as the getter's type reads it (255 as an i8 is -1)."""
    b = BITS.get(tipo, 32)
    v &= (1 << b) - 1
    if tipo.startswith('i') and v >= 1 << (b - 1):
        v -= 1 << b
    return v


def main():
    arqs = [a for a in sys.argv[1:] if not a.startswith('--')]
    grava = '--gravar' in sys.argv
    getters = tipos_dos_getters()
    tabelas = {}  # (type, getter) -> (module, module type, {value: name}, getter type)
    modulos = {}  # module -> (type, {value: (name, meaning, confidence)}, [(type, getter)])
    for a in arqs:
        for chave, tab in json.load(open(a, encoding='utf-8')).items():
            if not isinstance(tab, dict) or 'values' not in tab:
                continue
            mod = tab.get('enum_name') or chave
            if chave == 'move_codes':
                alvo, tipo_g = ('MatchPlayer', 'move_skill'), 'usize'
            elif chave in CAMPOS:
                alvo = CAMPOS[chave]
                tipo_g = getters.get(alvo, tab.get('rust_type', 'i32'))
            else:
                continue
            # a field that shares another's enum (the in-match action holds the move code) joins its module
            if mod not in modulos:
                modulos[mod] = (tipo_g, {}, [])
            tipo_m, vals, alvos = modulos[mod]
            alvos.append((alvo, tipo_g))
            for num, v in tab['values'].items():
                val = int(num, 0) if tipo_m == 'usize' else normal(int(num, 0), tipo_m)
                nome = re.sub(r'[^A-Z0-9_]', '_', v['name'].upper())
                if val in vals or nome in {x[0] for x in vals.values()}:
                    continue
                vals[val] = (nome, re.sub(r'\s+', ' ', v.get('meaning', '')).strip().rstrip('.'), v.get('confidence', 'read'))
    L = ['use super::*;', '',
         '// The match engine\'s magic numbers by name, generated by engenharia-reversa/aplicar_codigos.py from readings of',
         '// the original routines (levas/reorganizacao/codigos_*.json). Each constant says what it means and how far to',
         '// trust the name: verified (two independent sources agree), read (one clear reading), inferred (a guess).',
         '// [pt] Os números mágicos do motor de partidas, com nome, significado e confiança.', '']
    for mod, (tipo_m, vals, alvos) in modulos.items():
        L += ['/// Values of %s.' % ', '.join('`%s.%s()`' % al for al, _ in alvos), '#[allow(dead_code)]', 'pub(crate) mod %s {' % mod]
        for val in sorted(vals):
            nome, sig, conf = vals[val]
            L += ['    /// %s. Name: %s.' % (sig[:1].upper() + sig[1:] if sig else nome, conf),
                  '    pub(crate) const %s: %s = %d;' % (nome, tipo_m, val)]
        L += ['}', '']
        for al, tipo_g in alvos:
            tabelas[al] = (mod, tipo_m, {v: n for v, (n, _, _) in vals.items()}, tipo_g)
    print('%d tabelas, %d constantes' % (len(modulos), sum(len(m[1]) for m in modulos.values())))
    if grava:
        open(SAIDA, 'w', encoding='utf-8').write('\n'.join(L) + '\n')
        os.system('python "%s" --gravar' % os.path.join(R, 'engenharia-reversa', 'modulos_motor.py'))
    n = 0
    for raiz, _, fs in os.walk(SRC):
        for f in fs:
            if not f.endswith('.rs') or f in ('records.rs', 'match_codes.rs', 'exe_calls.rs'):
                continue
            p = os.path.join(raiz, f)
            t = open(p, encoding='utf-8').read()
            partes, pos = [], 0
            for _, a, b in mover_rotinas.blocos(t):
                bl = t[a:b]
                mk = tr.mascara(bl)
                tip = {}
                for m in re.finditer(r'(?<![\w.])([a-z_][a-z0-9_]*)\s*:\s*(Engine|MatchPlayer)\b', mk):
                    tip[m.group(1)] = m.group(2)
                for m in re.finditer(r'\blet\s+([a-z_][a-z0-9_]*)\s*=\s*(Engine|MatchPlayer)\(', mk):
                    tip[m.group(1)] = m.group(2)
                if not tip:
                    continue
                nomes_v = '|'.join(map(re.escape, tip))
                ed = []
                # comparisons: x.f() [as T] OP LIT   /   (x.f() as T) OP LIT
                for m in re.finditer(r'(?<![\w.])(%s)\.([a-z_0-9]+)\(\)(\s*as\s*(\w+))?(\))?\s*(==|!=)\s*(-?(?:0x[0-9a-f]+|\d+))\b' % nomes_v, mk):
                    alvo = (tip[m.group(1)], m.group(2))
                    if alvo not in tabelas:
                        continue
                    mod, tipo_m, nomes, tipo = tabelas[alvo]
                    val = normal(int(m.group(7), 0), tipo)
                    if tipo_m != tipo:
                        val = int(m.group(7), 0)
                    if val not in nomes:
                        continue
                    cast = m.group(4) or (tipo if tipo_m != tipo else None)
                    rhs = '%s::%s' % (mod, nomes[val]) + (' as %s' % cast if cast and cast != tipo_m else '')
                    ed.append((m.start(7), m.end(7), rhs))
                # assignments: x.set_f(LIT) / x.set_f((LIT) as T)
                for m in re.finditer(r'(?<![\w.])(%s)\.set_([a-z_0-9]+)\((\(?(-?(?:0x[0-9a-f]+|\d+))\)?(?:\s*as\s*\w+)?)\)' % nomes_v, mk):
                    alvo = (tip[m.group(1)], m.group(2))
                    if alvo not in tabelas:
                        continue
                    mod, tipo_m, nomes, tipo = tabelas[alvo]
                    val = normal(int(m.group(4), 0), tipo) if tipo_m == tipo else int(m.group(4), 0)
                    if val in nomes:
                        ed.append((m.start(3), m.end(3), '%s::%s' % (mod, nomes[val]) + ('' if tipo_m == tipo else ' as %s' % tipo)))
                # move codes: x.move_skill(N) / x.set_move_skill(N, v)
                if ('MatchPlayer', 'move_skill') in tabelas:
                    mod, _, nomes, _ = tabelas[('MatchPlayer', 'move_skill')]
                    for m in re.finditer(r'(?<![\w.])(%s)\.(?:set_)?move_skill\((\d+)\b' % nomes_v, mk):
                        if tip[m.group(1)] == 'MatchPlayer' and int(m.group(2)) in nomes:
                            ed.append((m.start(2), m.end(2), '%s::%s' % (mod, nomes[int(m.group(2))])))
                if not ed:
                    continue
                novo = bl
                for a2, b2, txt in sorted(set(ed), reverse=True):
                    novo = novo[:a2] + txt + novo[b2:]
                n += len(ed)
                partes += [t[pos:a], novo]
                pos = b
            partes.append(t[pos:])
            if grava and ''.join(partes) != t:
                open(p, 'w', encoding='utf-8').write(''.join(partes))
    print('%d literais viraram nomes' % n)


if __name__ == '__main__':
    main()
