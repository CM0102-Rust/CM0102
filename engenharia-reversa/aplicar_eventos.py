r"""The match commentary codes by name (09/11/2026, the outside reader's round 10, item 4: "event/commentary ids are bare
hex"). The game's own Data/events_eng.cfg names every match event (`# EVENT_HAND_BALL` above `= 72, ...`); the code the
exe passes to Match_Events::add_event is 8000 + the event number. This tool generates rust/src/motor/events.rs (module
`event`, one constant per event: `event::HAND_BALL = 8072`, its level "game": the name comes from the game's own file;
only the identifiers are taken, none of the commentary texts) and replaces the literals ONLY where the value is
known to be a commentary code: the argument in the position of a parameter named `code`/`codigo` (or `abertura`,
`common`, `quieta`) of a narration closure or function, and the first element of the array passed with
FN_MATCH_EVENTS_ADD_EVENT. Other numbers in the same range (grid offsets 0x21b6, reputations 8000, flags 0x2000) stay.
Usage: python aplicar_eventos.py [--gravar]
[pt] Os códigos de narração com nome, tirados do events_eng.cfg do próprio jogo (só os identificadores); troca os
literais só onde o valor é com certeza um código de narração (o parâmetro `code` das closures e funções de narração).
"""
import os
import re
import sys

R = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(R, 'rust', 'src')
CFG = os.path.join(R, 'jogo', 'Data', 'events_eng.cfg')
SAIDA = os.path.join(SRC, 'motor', 'events.rs')
sys.path.insert(0, os.path.join(R, 'engenharia-reversa'))
import involucros_exe as ie  # noqa: E402
import mover_rotinas  # noqa: E402
import tipar_registros as tr  # noqa: E402

PARAMS_CODIGO = {'code', 'codigo', 'abertura', 'common', 'quieta'}


def eventos():
    ev, nome = {}, None
    for l in open(CFG, encoding='latin-1'):
        m = re.match(r'#\s*(EVENT_[A-Z0-9_]+)\s*$', l)
        if m:
            nome = m.group(1)
            continue
        m = re.match(r'=\s*(\d+),', l)
        if m and nome:
            ev[int(m.group(1))] = nome[len('EVENT_'):]
            nome = None
    return ev


def posicoes(params):
    """Positions of the commentary-code parameters in a parameter list text."""
    out = []
    for k, p in enumerate(ie.args_da_chamada('(' + params + ')', 0)[0] or []):
        nm = p.split(':')[0].strip().replace('mut ', '')
        if nm in PARAMS_CODIGO or nm.startswith('codigo'):
            out.append(k)
    return out


def main():
    grava = '--gravar' in sys.argv
    ev = eventos()
    nomes, vistos = {}, set()
    for i in sorted(ev):
        n = re.sub(r'[^A-Z0-9_]', '_', ev[i])
        if n in vistos or n[:1].isdigit():
            n = 'E%d_%s' % (i, n)
        vistos.add(n)
        nomes[8000 + i] = n
    L = ['use super::*;', '',
         '// The match commentary codes by name, generated by engenharia-reversa/aplicar_eventos.py from the identifiers of',
         '// the game\'s own Data/events_eng.cfg (`# EVENT_...` above `= <number>, ...`): the code passed to',
         '// Match_Events::add_event is 8000 + the event number. Name level: game (the game\'s own file names it).',
         '// [pt] Os códigos de narração da partida, com o nome do events_eng.cfg do próprio jogo (só os identificadores).', '',
         '#[allow(dead_code)]', 'pub(crate) mod event {']
    for v in sorted(nomes):
        L += ['    /// Event %d of events_eng.cfg. Name: game.' % (v - 8000), '    pub(crate) const %s: u32 = %d;' % (nomes[v], v)]
    L += ['}', '']
    # global functions with a commentary-code parameter
    globais = {}
    for raiz, _, fs in os.walk(SRC):
        for f in fs:
            if f.endswith('.rs'):
                t = tr.mascara(open(os.path.join(raiz, f), encoding='utf-8').read())
                for m in re.finditer(r'\bfn (\w+)\(', t):
                    args, _ = ie.args_da_chamada(t, m.end() - 1)
                    ps = posicoes(','.join(args or []))
                    if ps:
                        globais[m.group(1)] = ps
    n = 0
    for raiz, _, fs in os.walk(SRC):
        for f in fs:
            if not f.endswith('.rs') or f in ('events.rs', 'exe_calls.rs', 'fields.rs', 'records.rs'):
                continue
            p = os.path.join(raiz, f)
            t = open(p, encoding='utf-8').read()
            partes, pos = [], 0
            for _, a, b in mover_rotinas.blocos(t):
                bl = t[a:b]
                mk = tr.mascara(bl)
                cons = dict(globais)
                for m in re.finditer(r'\blet (\w+) = (?:move )?\|([^|]*)\|', mk):
                    ps = posicoes(m.group(2))
                    if ps:
                        cons[m.group(1)] = ps
                    elif m.group(1) in cons:
                        del cons[m.group(1)]  # a local closure with the same name that is not a narrator
                ed = []

                def trocar_em(ini, fim):
                    for mm in re.finditer(r'(?<![\w.])(0x[0-9a-f]+|\d{4})(u32)?\b', mk[ini:fim]):
                        v = int(mm.group(1), 0)
                        if v in nomes:
                            ed.append((ini + mm.start(), ini + mm.end(), 'event::%s' % nomes[v]))
                for m in re.finditer(r'(?<![\w.:])(\w+)\(', mk):
                    if m.group(1) not in cons:
                        continue
                    args, fim = ie.args_da_chamada(mk, m.end() - 1)
                    if not args:
                        continue
                    pos_a = m.end()
                    limites = []
                    for k, x in enumerate(args):
                        i0 = mk.index(x, pos_a)
                        limites.append((i0, i0 + len(x)))
                        pos_a = i0 + len(x)
                    for k in cons[m.group(1)]:
                        if k < len(limites):
                            trocar_em(*limites[k])
                # call(FN_MATCH_EVENTS_ADD_EVENT, x, [CODE, ...])
                for m in re.finditer(r'FN_MATCH_EVENTS_ADD_EVENT\s*,[^\[\]]*?\[\s*(0x[0-9a-f]+|\d{4})\b', mk):
                    v = int(m.group(1), 0)
                    if v in nomes:
                        ed.append((m.start(1), m.end(1), 'event::%s' % nomes[v]))
                if not ed:
                    continue
                novo = bl
                for a2, b2, txt in sorted(set(ed), reverse=True):
                    novo = novo[:a2] + txt + novo[b2:]
                n += len(set(ed))
                partes += [t[pos:a], novo]
                pos = b
            partes.append(t[pos:])
            if grava and ''.join(partes) != t:
                open(p, 'w', encoding='utf-8').write(''.join(partes))
    print('%d eventos; %d literais viraram nomes' % (len(nomes), n))
    if grava:
        open(SAIDA, 'w', encoding='utf-8').write('\n'.join(L) + '\n')
        os.system('python "%s" --gravar' % os.path.join(R, 'engenharia-reversa', 'modulos_motor.py'))


if __name__ == '__main__':
    main()
