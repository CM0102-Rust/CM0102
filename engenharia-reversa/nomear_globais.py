r"""Troca os endereços crus das globais do exe no motor (0xae23b4...) por constantes com nome (G_CLUB_TABLE...), em
rust/src/motor/globals.rs (etapa 4 da reorganização, rodada 2, 07/11/2026). Nomes, tipos e descrições do mapa de dados
de maxevans60 (data-map/data.tsv, CC BY 4.0, ver CREDITOS.md). As chaves fixas (0x9cf...) ficam com o keys.rs; os
comentários e os arquivos gerados não mudam. Onde o código pedia u32, a troca leva `as u32` (nomear_chaves.py --tipos).

Uso: python nomear_globais.py --gravar
"""
import csv
import os
import re
import sys

R = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(R, 'rust', 'src')
# só onde o número é usado como endereço: lido/gravado pelas funções de memória ou convertido em ponteiro (um número
# que por acaso coincide com uma global, como 0xb71b00 = 12.000.000 da TV, fica como está)
LEITURA = re.compile(r'\b((?:read|write)_\w+|u|i|w|byte)\((0x[0-9a-f]{6})(usize)?\b')
PONTEIRO = re.compile(r'\b(0x[0-9a-f]{6})(usize)?\b(?= as \*)')
NAO = {'vtable', 'string', 'float', 'double', 'code'}  # só dados: tabelas de método, textos e constantes ficam


def arquivos():
    yield os.path.join(SRC, 'motor.rs')
    for d, _, fs in os.walk(os.path.join(SRC, 'motor')):
        for f in fs:
            if f.endswith('.rs') and f not in ('globals.rs', 'keys.rs', 'exe_fns.rs'):
                yield os.path.join(d, f)


def mapa():
    m, vistos = {}, set()
    p = os.path.join(R, 'referencias', 'cm0102-function-map', 'data-map', 'data.tsv')
    for r in csv.DictReader(open(p, encoding='utf-8'), delimiter='\t'):
        a = int(r['address'], 16)
        if (0x9cf000 <= a < 0x9d0000) or r['type'] in NAO or not r['name'] or 'char' in r['type'] \
                or 'not_a_global' in r['name'].lower() or 'not a global' in (r.get('description') or '').lower():
            continue
        n = re.sub(r'[^A-Za-z0-9]+', '_', r['name']).strip('_').upper()
        n = 'G_' + (n[2:] if n.startswith('G_') else n)
        if n in vistos:
            n = '%s_%X' % (n, a)
        vistos.add(n)
        m[a] = (n, r['type'], (r.get('description') or '').strip())
    return m


def main():
    m = mapa()
    usadas = {}

    def trocar_linha(l):
        cod, sep, com = l.partition('//')

        def nome(lit):
            a = int(lit, 16)
            if a not in m:
                return None
            usadas[a] = m[a]
            return m[a][0]
        cod = LEITURA.sub(lambda x: '%s(%s' % (x.group(1), nome(x.group(2))) if nome(x.group(2)) else x.group(0), cod)
        cod = PONTEIRO.sub(lambda x: nome(x.group(1)) or x.group(0), cod)
        return cod + sep + com

    for p in arquivos():
        t = open(p, encoding='utf-8').read()
        if p.endswith('motor.rs'):  # a tabela PROLOGOS (endereços de rotina) não é global
            i = t.index('const N')
            novo = t[:i] + '\n'.join(trocar_linha(l) for l in t[i:].split('\n'))
        else:
            novo = '\n'.join(trocar_linha(l) for l in t.split('\n'))
        if novo != t and '--gravar' in sys.argv:
            open(p, 'w', encoding='utf-8').write(novo)
    print('%d globais com nome' % len(usadas))
    if '--gravar' not in sys.argv:
        return
    import trocar_nas_mutacoes
    trocar_nas_mutacoes.aplicar(trocar_linha)
    cab = ('use super::*;\n\n'
           '// The exe\'s global variables the engine reads and writes, by name (address in cm0102.exe 3.9.68, its type and what\n'
           '// it holds). From maxevans60\'s data map (CC BY 4.0, see CREDITOS.md). Generated by engenharia-reversa/nomear_globais.py.\n'
           '// [pt] As variáveis globais do exe que o motor lê e grava, pelo nome (endereço, tipo e o que guardam).\n\n')
    corpo = ''.join('/// %s (%s)\npub(crate) const %s: usize = %#x;\n' % (d or n, t, n, a) for a, (n, t, d) in sorted(usadas.items()))
    open(os.path.join(SRC, 'motor', 'globals.rs'), 'w', encoding='utf-8').write(cab + corpo)


if __name__ == '__main__':
    main()
