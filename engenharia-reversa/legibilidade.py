r"""Placar de legibilidade do motor (etapa 4 da reorganização, 07/11/2026): docs/LEGIBILIDADE.md e .en.md.

Mede, por arquivo de rust/src/motor/ (e o motor.rs), o que ainda atrapalha quem lê de fora:
- deslocamentos crus: `+ 0x..` (campo de registro sem nome);
- chaves fixas: `0x9cf...` (ponteiro de nação/clube sem nome);
- chamadas por endereço: `transmute(0x...usize)` (função do exe sem nome);
- cópias de acesso à memória: funções `<item>_d/_w/_b/_pd/...` repetidas em cada item;
- rotinas portadas sem cabeçalho (`///` logo acima do `fn`).
Cada rodada da etapa 4 deve baixar esses números; o placar sai a cada leva.

Uso: python legibilidade.py
"""
import os
import re

R = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(R, 'rust', 'src')
MEDIDAS = [
    ('desloc', r'\+ 0x[0-9a-f]+\b', 'deslocamentos crus', 'raw offsets'),
    ('chaves', r'\b0x9cf[0-9a-f]{3}\b', 'chaves fixas cruas', 'raw fixed keys'),
    ('enderecos', r'transmute\(0x[0-9a-f]+usize\)', 'chamadas por endereço', 'calls by address'),
    ('copias', r'^unsafe fn \w+_(?:d|w|b|f|pd|pw|pb|pf)\(', 'cópias de acesso à memória', 'memory-access copies'),
]


def arquivos():
    yield os.path.join(SRC, 'motor.rs')
    for d, _, fs in sorted(os.walk(os.path.join(SRC, 'motor'))):
        for f in sorted(fs):
            if f.endswith('.rs'):
                yield os.path.join(d, f)


def portadas():
    s = open(os.path.join(SRC, 'motor.rs'), encoding='utf-8').read()
    n = len(re.findall(r'Prologo \{ endereco:', s[:s.index('const N')]))
    return set(re.findall(r'(\w+) as \*const', s[s.index('let rust: [usize; N] = ['):])[:n])


def medir():
    nomes = portadas()
    linhas = []
    for f in arquivos():
        t = open(f, encoding='utf-8').read()
        m = {k: len(re.findall(rx, t, re.M)) for k, rx, _, _ in MEDIDAS}
        sem = 0
        for x in re.finditer(r'^(?:pub )?(?:unsafe )?(?:extern "\w+" )?fn (\w+)', t, re.M):
            if x.group(1) in nomes:
                antes = t[:x.start()].rstrip('\n').rsplit('\n', 1)[-1]
                sem += not antes.lstrip().startswith(('///', '#['))
        m['sem_cabecalho'] = sem
        m['linhas'] = t.count('\n')
        linhas.append((os.path.relpath(f, SRC).replace('\\', '/'), m))
    return linhas


def gerar(linhas, en):
    chaves = [k for k, *_ in MEDIDAS] + ['sem_cabecalho']
    tit = [(e if en else p) for _, _, p, e in MEDIDAS] + ['routines without header' if en else 'rotinas sem cabeçalho']
    tot = {k: sum(m[k] for _, m in linhas) for k in chaves + ['linhas']}
    L = ['*English version of [LEGIBILIDADE.md](LEGIBILIDADE.md). Both are kept in sync; the Portuguese file is the original.*' if en
         else '*[English version](LEGIBILIDADE.en.md).*', '',
         '# Readability scoreboard' if en else '# Placar de legibilidade', '',
         ('Generated by `python engenharia-reversa/legibilidade.py`. What still gets in the way of an outside reader of the engine '
          '(`rust/src/motor.rs` and `rust/src/motor/`); each round of stage 4 of the reorganisation should lower these numbers.') if en else
         ('Gerado por `python engenharia-reversa/legibilidade.py`. O que ainda atrapalha quem lê o motor de fora (`rust/src/motor.rs` e '
          '`rust/src/motor/`); cada rodada da etapa 4 da reorganização deve baixar esses números.'), '',
         '## ' + ('Total' if en else 'Total'), '',
         '| %s | %s |' % ('Measure' if en else 'Medida', 'Count' if en else 'Quantidade'), '|---|---:|']
    L += ['| %s | %d |' % (t, tot[k]) for k, t in zip(chaves, tit)]
    L += ['| %s | %d |' % ('lines' if en else 'linhas', tot['linhas']), '',
          '## ' + ('By file (the 40 worst, by raw offsets)' if en else 'Por arquivo (os 40 piores, pelos deslocamentos crus)'), '',
          '| %s | %s | %s |' % ('File' if en else 'Arquivo', ' | '.join(tit), 'lines' if en else 'linhas'),
          '|---|' + '---:|' * (len(chaves) + 1)]
    for f, m in sorted(linhas, key=lambda x: -x[1]['desloc'])[:40]:
        L.append('| `%s` | %s | %d |' % (f, ' | '.join(str(m[k]) for k in chaves), m['linhas']))
    return '\n'.join(L) + '\n'


if __name__ == '__main__':
    ls = medir()
    for en, nome in ((False, 'LEGIBILIDADE.md'), (True, 'LEGIBILIDADE.en.md')):
        open(os.path.join(R, 'docs', nome), 'w', encoding='utf-8').write(gerar(ls, en))
    tot = {k: sum(m[k] for _, m in ls) for k in ('desloc', 'chaves', 'enderecos', 'copias', 'sem_cabecalho')}
    print(' '.join('%s=%d' % x for x in tot.items()))
