r"""Placar por arquivo-fonte do exe inteiro, com as fronteiras e os arquivos do mapa de maxevans60
(referencias/cm0102-function-map, CC BY 4.0): uma função conta como portada quando o início dela tem
Prologo em rust/src/motor.rs (a rotina inteira roda em Rust). Grava docs/PLACAR_ARQUIVOS.md e .en.md.

Uso: python placar_arquivos.py
"""
import collections
import csv
import os
import re

R = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def barra(p):
    cheios = int(p // 10)
    meio = 1 if 0 < p - cheios * 10 and cheios < 10 else 0
    return '🟩' * cheios + '🟨' * meio + '⬜' * (10 - cheios - meio)


def calcular():
    feitas = {int(x, 16) for x in re.findall(r'Prologo \{ endereco: (0x[0-9a-f]+)', open(os.path.join(R, 'rust', 'src', 'motor.rs'), encoding='utf-8').read())}
    por = collections.defaultdict(lambda: [0, 0, 0, 0])  # funções, portadas, bytes, bytes portados
    linhas = list(csv.DictReader(open(os.path.join(R, 'referencias', 'cm0102-function-map', 'map', 'functions.tsv'), encoding='utf-8'), delimiter='\t'))
    # o campo size do mapa conta instrucoes; o tamanho em bytes vai ate o proximo inicio verdadeiro. As entradas
    # que o proprio mapa marca como falsas (fragmento, meio de instrucao, enchimento) ficam com a funcao anterior.
    def falsa(r):
        return bool(re.search(r'fragment|mid_instruction|nop_padding', r['name'])) or r['purpose'].startswith(
            ('Holds no function', 'Is an address in the middle', 'Misread entry', 'Marks a false entry', 'Is a tail block', 'Falls in the middle'))
    reais = sorted(int(r['address'], 16) for r in linhas if not falsa(r))
    fim = dict(zip(reais, reais[1:] + [0x967000]))
    for r in linhas:
        if falsa(r):
            continue
        a = int(r['address'], 16)
        n = fim[a] - a
        arq = r['doc'] or '(biblioteca)'
        t = por[arq]
        t[0] += 1
        t[2] += n
        if a in feitas:
            t[1] += 1
            t[3] += n
    return por


def main():
    por = calcular()
    total = [sum(t[i] for t in por.values()) for i in range(4)]
    com = sorted(((a, t) for a, t in por.items() if t[1]), key=lambda x: -x[1][3] / x[1][2])
    sem = len([a for a, t in por.items() if not t[1]])
    for ling in ('pt', 'en'):
        pt = ling == 'pt'
        L = ['# Placar por arquivo (exe inteiro)' if pt else '# Scoreboard by file (whole exe)', '',
             ('Gerado por `python engenharia-reversa/placar_arquivos.py` com as fronteiras e os arquivos-fonte do mapa de '
              '[maxevans60](https://github.com/maxevans60/cm0102-function-map) (CC BY 4.0). Uma função conta quando o início dela '
              'é desviado para Rust (`Prologo` em `rust/src/motor.rs`). O placar do motor de partidas, pelas nossas fronteiras, '
              'fica em `PLACAR.md`.') if pt else
             ('Generated by `python engenharia-reversa/placar_arquivos.py` with the boundaries and source files of '
              '[maxevans60](https://github.com/maxevans60/cm0102-function-map)\'s map (CC BY 4.0). A function counts when its start '
              'is hooked to Rust (`Prologo` in `rust/src/motor.rs`). The match engine scoreboard, by our boundaries, is in `PLACAR.en.md`.'),
             '',
             (f'**Exe inteiro:** {total[1]} de {total[0]} funções, {total[3] / 1024:.1f} de {total[2] / 1024:.1f} KB '
              f'(**{100 * total[3] / total[2]:.2f}%**) · {len(com)} de {len(por)} arquivos com rotinas em Rust') if pt else
             (f'**Whole exe:** {total[1]} of {total[0]} functions, {total[3] / 1024:.1f} of {total[2] / 1024:.1f} KB '
              f'(**{100 * total[3] / total[2]:.2f}%**) · {len(com)} of {len(por)} files with routines in Rust'),
             '',
             '| Arquivo | Funções | KB | Progresso |' if pt else '| File | Functions | KB | Progress |', '|---|---|---|---|']
        for a, t in com:
            p = 100 * t[3] / t[2]
            L.append(f'| `{a}` | {t[1]}/{t[0]} | {t[3] / 1024:.1f}/{t[2] / 1024:.1f} | {barra(p)} **{p:.1f}%** |')
        L += ['', (f'Os outros {sem} arquivos ainda não têm rotina em Rust.') if pt else (f'The other {sem} files have no routine in Rust yet.'), '']
        nome = 'PLACAR_ARQUIVOS.md' if pt else 'PLACAR_ARQUIVOS.en.md'
        open(os.path.join(R, 'docs', nome), 'w', encoding='utf-8').write('\n'.join(L))
    print(f'{total[1]}/{total[0]} funcoes, {100 * total[3] / total[2]:.2f}% do exe; {len(com)} arquivos com Rust')


if __name__ == '__main__':
    main()
